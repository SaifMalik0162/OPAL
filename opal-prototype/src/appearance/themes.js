export const THEME_BY_ID = Object.freeze(Object.fromEntries(THEMES.map((theme) => [theme.id, theme])));
const FALLBACK_ACCENT = "#C3BBEF";
const CUSTOM_BASE = THEME_BY_ID.obsidian;

function linearize(channel) {
  const value = channel / 255;
  return value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4;
}

function luminance(hex) {
  const color = normalizeHexColor(hex) ?? "#000000";
  const red = Number.parseInt(color.slice(1, 3), 16);
  const green = Number.parseInt(color.slice(3, 5), 16);
  const blue = Number.parseInt(color.slice(5, 7), 16);
  return 0.2126 * linearize(red) + 0.7152 * linearize(green) + 0.0722 * linearize(blue);
}

export function normalizeHexColor(value) {
  return typeof value === "string" && /^#[0-9a-f]{6}$/i.test(value) ? value.toUpperCase() : null;
}

export function contrastRatio(first, second) {
  const [lighter, darker] = [luminance(first), luminance(second)].sort((a, b) => b - a);
  return (lighter + 0.05) / (darker + 0.05);
}

function mixHex(hex, target, amount) {
  const start = [1, 3, 5].map((index) => Number.parseInt(hex.slice(index, index + 2), 16));
  const end = [1, 3, 5].map((index) => Number.parseInt(target.slice(index, index + 2), 16));
  return `#${start.map((channel, index) => Math.round(channel + (end[index] - channel) * amount).toString(16).padStart(2, "0")).join("")}`.toUpperCase();
}

function ensureAccentContrast(candidate, surface) {
  if (contrastRatio(candidate, surface) >= 3) return candidate;
  const options = [];
  for (const target of ["#FFFFFF", "#000000"]) {
    for (let step = 1; step <= 100; step += 1) {
      const adjusted = mixHex(candidate, target, step / 100);
      if (contrastRatio(adjusted, surface) >= 3) {
        options.push({ color: adjusted, amount: step });
        break;
      }
    }
  }
  options.sort((first, second) => first.amount - second.amount);
  return options[0]?.color ?? FALLBACK_ACCENT;
}

export function accessibleAccentColor(candidate, surface) {
  const normalizedCandidate = normalizeHexColor(candidate) ?? FALLBACK_ACCENT;
  const normalizedSurface = normalizeHexColor(surface) ?? THEME_BY_ID.obsidian.colors.canvas;
  return ensureAccentContrast(normalizedCandidate, normalizedSurface);
}

export function accentForegroundColor(accent) {
  const normalizedAccent = normalizeHexColor(accent) ?? FALLBACK_ACCENT;
  const lightRatio = contrastRatio("#FFFFFF", normalizedAccent);
  const dark = contrastRatio("#211931", normalizedAccent) >= 4.5 ? "#211931" : "#000000";
  return lightRatio >= contrastRatio(dark, normalizedAccent) ? "#FFFFFF" : dark;
}

export function customImageScrim(dim) {
  const normalizedDim = Number.isFinite(dim) ? Math.max(0.2, Math.min(0.7, dim)) : 0.4;
  const effectiveDim = 0.58 + (normalizedDim - 0.2) * 0.24;
  return Math.max(0, (effectiveDim - normalizedDim) / (1 - normalizedDim));
}

export function customPlayerPalette(candidate) {
  const hue = normalizeHexColor(candidate) ?? FALLBACK_ACCENT;
  const base = "#101117";
  const edge = mixHex(base, hue, 0.22);
  const tint = mixHex(base, hue, 0.38);
  const center = mixHex(base, hue, 0.18);
  const accent = accessibleAccentColor(hue, tint);
  const highlight = mixHex(accent, "#FFFFFF", 0.2);
  return {
    "--custom-player-glass": `linear-gradient(112deg, ${rgbaFromHex(edge, 0.91)}, ${rgbaFromHex(tint, 0.87)})`,
    "--custom-player-solid": `linear-gradient(112deg, ${edge}, ${tint})`,
    "--custom-player-center": center,
    "--custom-player-accent": accent,
    "--custom-player-highlight": highlight,
    "--custom-player-ink": accentForegroundColor(highlight),
  };
}

function rgbaFromHex(hex, alpha) {
  const normalized = normalizeHexColor(hex) ?? FALLBACK_ACCENT;
  const red = Number.parseInt(normalized.slice(1, 3), 16);
  const green = Number.parseInt(normalized.slice(3, 5), 16);
  const blue = Number.parseInt(normalized.slice(5, 7), 16);
  return `rgba(${red}, ${green}, ${blue}, ${alpha})`;
}

function variablesForTheme(theme, custom) {
  const colors = theme.colors;
  const accent = custom
    ? accessibleAccentColor(custom.accentOverride ?? custom.suggestedAccent, colors.accentSurface ?? colors.canvas)
    : colors.accent;
  const accentForeground = custom
    ? accentForegroundColor(accent)
    : colors.accentForeground;
  const accentGloss = mixHex(accent, luminance(accentForeground) > luminance(accent) ? "#000000" : "#FFFFFF", 0.19);
  return {
    "--night": colors.canvas,
    "--night-soft": colors.nightSoft,
    "--plum": colors.plum,
    "--plum-light": colors.plumLight,
    "--plum-copy": colors.plumCopy ?? colors.muted,
    "--ivory": colors.text,
    "--lavender": accent,
    "--lavender-bright": custom ? mixHex(accent, colors.text, 0.16) : colors.accentBright,
    "--glass": colors.glass,
    "--glass-strong": colors.glassStrong,
    "--player-surface": colors.playerSurface,
    "--line": colors.line,
    "--muted": colors.muted,
    "--shadow": colors.shadow,
    "--surface-deep": colors.surfaceDeep,
    "--surface-raised": colors.surfaceRaised,
    "--surface-glass": colors.surfaceGlass,
    "--surface-line": colors.surfaceLine,
    "--opal-accent": accent,
    "--accent": accent,
    "--opal-accent-bright": custom ? mixHex(accent, colors.text, 0.16) : colors.accentBright,
    "--accent-foreground": accentForeground,
    "--accent-gloss": accentGloss,
    "--text-overlay-ink": colors.overlayInk,
    "--surface-inset-ink": colors.insetInk,
    "--danger-text": colors.dangerText,
    "--success-text": colors.successText,
    "--warning-text": colors.warningText,
    "--app-overlay": colors.appOverlay,
    "--background-gradient": colors.background,
    "--background-glow-top": colors.glowTop,
    "--background-glow-bottom": colors.glowBottom,
    "--accent-wash": rgbaFromHex(accent, 0.16),
    "--accent-outline": rgbaFromHex(accent, 0.48),
    "--accent-pressed": rgbaFromHex(accent, 0.24),
    ...customPlayerPalette(custom?.accentOverride ?? custom?.suggestedAccent),
  };
}

export function applyAppearanceToDocument(appearance, { backgroundUrl = null, allowIncomplete = false } = {}) {
  const root = document.documentElement;
  const isCustom = appearance?.themeId === "custom";
  const canShowCustom = isCustom && (backgroundUrl || allowIncomplete);
  const theme = canShowCustom ? CUSTOM_BASE : THEME_BY_ID[appearance?.themeId] ?? THEME_BY_ID.opal;
  const custom = canShowCustom ? appearance.custom ?? {} : null;
  const themeId = canShowCustom ? "custom" : theme.id;

  root.dataset.appearanceTheme = themeId;
  root.dataset.appearanceScheme = theme.scheme;
  root.style.colorScheme = theme.scheme;
  for (const [name, value] of Object.entries(variablesForTheme(theme, custom))) root.style.setProperty(name, value);

  root.style.setProperty("--appearance-image-position", `${custom?.x ?? 50}% ${custom?.y ?? 50}%`);
  root.style.setProperty("--appearance-image-dim", String(custom?.dim ?? 0.4));
  root.style.setProperty("--appearance-image-blur", `${custom?.blur ?? 8}px`);
  root.style.setProperty("--appearance-image-scrim", String(customImageScrim(custom?.dim ?? 0.4)));
}

export function initializeAppearance(appearance) {
  applyAppearanceToDocument(appearance, { allowIncomplete: appearance?.themeId === "custom" });
}
