use super::{initialise_storage, now_ms, open_database, StorageRoots};

const FIXTURE_MARKER: &str = "Generated by OPAL's development fixture tool. Safe to recreate.\n";
const SAMPLE_RATE: u32 = 22_050;
const SAMPLE_SECONDS: u32 = 8;

pub fn generate_fixture_libraries() -> Result<Vec<(String, PathBuf)>, String> {
    let output_root = match std::env::var_os("OPAL_FIXTURE_OUTPUT_ROOT") {
        Some(path) => PathBuf::from(path),
        None => dirs::data_dir()
            .ok_or_else(|| "Could not locate the platform app-data folder.".to_string())?
            .join("com.opal.library.development")
            .join("opal-fixtures"),
    };
    if output_root.exists() {
        let marker = fs::read_to_string(output_root.join(".opal-fixtures")).map_err(|_| {
            format!(
                "Refusing to replace unrecognized folder: {}",
                output_root.display()
            )
        })?;
        if marker != FIXTURE_MARKER {
            return Err(format!(
                "Refusing to replace unrecognized folder: {}",
                output_root.display()
            ));
        }
        fs::remove_dir_all(&output_root)
            .map_err(|error| format!("Could not recreate generated fixtures: {error}"))?;
    }
    fs::create_dir_all(&output_root)
        .map_err(|error| format!("Could not create fixture output folder: {error}"))?;
    fs::write(output_root.join(".opal-fixtures"), FIXTURE_MARKER)
        .map_err(|error| format!("Could not mark generated fixture folder: {error}"))?;

    let mut paths = Vec::new();
    for scenario in [
        "empty",
        "small",
        "crowded",
        "hundred-tracks",
        "audio-corpus",
        "versions",
        "long-titles",
        "many-moments",
    ] {
        let library_root = output_root.join(scenario);
        let roots = StorageRoots {
            db_path: library_root.join("opal.sqlite"),
            audio_dir: library_root.join("audio"),
            artwork_dir: library_root.join("artwork"),
            staging_dir: library_root.join(".staging"),
            root: library_root.clone(),
        };
        initialise_storage(&roots)?;
        seed_scenario(scenario, &roots)?;
        paths.push((scenario.to_string(), library_root));
    }
    Ok(paths)
}

fn seed_scenario(scenario: &str, roots: &StorageRoots) -> Result<(), String> {
    match scenario {
        "empty" => Ok(()),
        "small" => {
            for index in 0..4 {
                seed_project(
                    roots,
                    &format!("small-{:02}", index + 1),
                    small_title(index),
                    4 + index,
                    1,
                    0,
                    false,
                )?;
            }
            Ok(())
        }
        "crowded" => {
            for index in 0..30 {
                let group_count = if index == 0 { 20 } else { 3 };
                seed_project(
                    roots,
                    &format!("crowded-{:02}", index + 1),
                    &format!("Session {:02} · {}", index + 1, collection_title(index)),
                    group_count,
                    1,
                    0,
                    false,
                )?;
            }
            Ok(())
        }
        "hundred-tracks" => seed_project(
            roots,
            "hundred-tracks-01",
            "The Long Shelf — 100 track workflow",
            100,
            1,
            0,
            false,
        ),
        "audio-corpus" => seed_project(
            roots,
            "audio-corpus-01",
            "Audio compatibility lab",
            1,
            1,
            0,
            false,
        ),
        "versions" => seed_project(
            roots,
            "versions-01",
            "Glasshouse — version study",
            5,
            3,
            0,
            false,
        ),
        "long-titles" => seed_project(
            roots,
            "long-titles-01",
            "A Room Full of Afternoon Light, Distant Trains, and Everything We Almost Said",
            6,
            1,
            0,
            true,
        ),
        "many-moments" => seed_project(
            roots,
            "many-moments-01",
            "Signal in the Quiet",
            3,
            1,
            56,
            false,
        ),
        _ => Err(format!("Unknown fixture scenario: {scenario}")),
    }
}

fn seed_project(
    roots: &StorageRoots,
    project_id: &str,
    title: &str,
    group_count: usize,
    versions_per_group: usize,
    moments_on_first_track: usize,
    long_track_titles: bool,
) -> Result<(), String> {
    let connection = open_database(&roots.db_path)?;
    let created_at = now_ms();
    let artwork_ref = format!("artwork/{project_id}.png");
    let artwork_source = artwork_source(project_id);
    let artwork_target = roots.root.join(&artwork_ref);
    fs::create_dir_all(artwork_target.parent().expect("artwork ref has parent"))
        .map_err(|error| format!("Could not create fixture artwork folder: {error}"))?;
    fs::copy(artwork_source, &artwork_target)
        .map_err(|error| format!("Could not copy fixture artwork: {error}"))?;
    connection
        .execute(
            "INSERT INTO projects (id, title, description, artwork_ref, created_at, updated_at) VALUES (?1, ?2, ?3, ?4, ?5, ?5)",
            params![project_id, title, fixture_description(project_id), artwork_ref, created_at],
        )
        .map_err(|error| format!("Could not create fixture project: {error}"))?;

    let mut track_position = 0_i64;
    let mut first_track_id = None;
    let mut group_ids = Vec::new();
    for group_index in 0..group_count {
        let group_id = format!("{project_id}-group-{:02}", group_index + 1);
        let group_title = fixture_track_title(group_index, long_track_titles);
        group_ids.push(group_id.clone());
        connection
            .execute(
                "INSERT INTO track_groups (id, project_id, title, position, created_at) VALUES (?1, ?2, ?3, ?4, ?5)",
                params![group_id, project_id, group_title, group_index as i64, created_at],
            )
            .map_err(|error| format!("Could not create fixture track group: {error}"))?;

        for version_index in 0..versions_per_group {
            let track_id = format!(
                "{project_id}-track-{:02}-v{:02}",
                group_index + 1,
                version_index + 1
            );
            if first_track_id.is_none() {
                first_track_id = Some(track_id.clone());
            }
            let version_name = match version_index {
                0 => "Original".to_string(),
                1 => "Warm Mix".to_string(),
                2 => "Final Bounce".to_string(),
                _ => format!("Bounce {}", version_index + 1),
            };
            let managed_file_ref = format!("audio/{project_id}/{track_id}.wav");
            let audio_path = roots.root.join(&managed_file_ref);
            fs::create_dir_all(audio_path.parent().expect("audio ref has parent"))
                .map_err(|error| format!("Could not create fixture audio folder: {error}"))?;
            let wave =
                write_original_wave(&audio_path, 180.0 + (track_position as f64 % 17.0) * 27.0)?;
            let source_hash = Sha256::digest(&wave)
                .iter()
                .map(|byte| format!("{byte:02x}"))
                .collect::<String>();
            let duration_ms = i64::from(SAMPLE_SECONDS) * 1_000;
            connection
                .execute(
                    "INSERT INTO tracks (id, project_id, group_id, title, position, version_name, version_position, is_current, duration_ms, format, managed_file_ref, source_hash, created_at) VALUES (?1, ?2, ?3, ?4, ?5, ?6, ?7, ?8, ?9, 'WAV', ?10, ?11, ?12)",
                    params![
                        track_id,
                        project_id,
                        group_id,
                        group_title,
                        track_position,
                        version_name,
                        version_index as i64,
                        if version_index == 0 { 1_i64 } else { 0_i64 },
                        duration_ms,
                        managed_file_ref,
                        source_hash,
                        created_at
                    ],
                )
                .map_err(|error| format!("Could not create fixture track: {error}"))?;
            track_position += 1;
        }
    }

    if let Some(track_id) = &first_track_id {
        connection
            .execute(
                "INSERT INTO notes (id, track_id, text, updated_at) VALUES (?1, ?2, ?3, ?4)",
                params![
                    format!("note-{project_id}"),
                    track_id,
                    "Listen for the lift into the next section.",
                    created_at
                ],
            )
            .map_err(|error| format!("Could not create fixture track note: {error}"))?;
        for index in 0..moments_on_first_track {
            let state = ["question", "change", "keep", "idea"][index % 4];
            let is_resolved = if index % 5 == 0 { 1_i64 } else { 0_i64 };
            let moment_id = format!("{project_id}-moment-{:03}", index + 1);
            let time_ms = 120 + ((index * 7_700 / moments_on_first_track.max(1)) as i64);
            connection
                .execute(
                    "INSERT INTO moments (id, track_id, lineage_id, time_ms, state, text, is_resolved, created_at, updated_at) VALUES (?1, ?2, ?3, ?4, ?5, ?6, ?7, ?8, ?8)",
                    params![moment_id, track_id, format!("lineage-{project_id}-{index:03}"), time_ms, state, moment_copy(index), is_resolved, created_at],
                )
                .map_err(|error| format!("Could not create fixture moment: {error}"))?;
        }
    }

    connection
        .execute(
            "INSERT INTO notes (id, project_id, text, updated_at) VALUES (?1, ?2, ?3, ?4)",
            params![
                format!("project-note-{project_id}"),
                project_id,
                "A working space for listening, notes, and the next decision.",
                created_at
            ],
        )
        .map_err(|error| format!("Could not create fixture project note: {error}"))?;

    if group_ids.len() > 1 {
        connection
            .execute(
                "INSERT INTO sequence_transitions (id, project_id, from_group_id, to_group_id, gap_ms, note, updated_at) VALUES (?1, ?2, ?3, ?4, 900, ?5, ?6)",
                params![format!("transition-{project_id}"), project_id, group_ids[0], group_ids[1], "Leave a little room for the reverb to settle.", created_at],
            )
            .map_err(|error| format!("Could not create fixture transition: {error}"))?;
    }
    Ok(())
}

fn artwork_source(project_id: &str) -> PathBuf {
    let names = ["night-bloom.png", "slow-light.png", "veil-atlas.png"];
    let index = project_id.bytes().map(usize::from).sum::<usize>() % names.len();
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join("public")
        .join("artwork")
        .join(names[index])
}

fn fixture_description(project_id: &str) -> &'static str {
    if project_id.starts_with("crowded-") {
        "A dense library fixture for collection scale and selection checks."
    } else if project_id.starts_with("long-titles-") {
        "Unicode, punctuation, and long-name layout fixture."
    } else {
        "An isolated OPAL development fixture with synthetic original audio."
    }
}

fn fixture_track_title(index: usize, long_titles: bool) -> String {
    if long_titles {
        format!(
            "{:02} — The Quiet Shape of Leaving Before the Last Train, with Strings That Bloom Slowly",
            index + 1
        )
    } else {
        let titles = [
            "Velvet Current",
            "A Small Blue Hour",
            "Soft Signal",
            "What the Room Kept",
            "Paper Moon Window",
            "The Long Way Home",
            "Afterglow Study",
            "Almost Morning",
        ];
        format!("{:02} · {}", index + 1, titles[index % titles.len()])
    }
}

