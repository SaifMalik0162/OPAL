fn write_original_wave(path: &Path, frequency: f64) -> Result<Vec<u8>, String> {
    let sample_count = SAMPLE_RATE * SAMPLE_SECONDS;
    let data_bytes = sample_count * 2;
    let mut file =
        File::create(path).map_err(|error| format!("Could not create fixture audio: {error}"))?;
    file.write_all(b"RIFF")
        .and_then(|_| file.write_all(&(36 + data_bytes).to_le_bytes()))
        .and_then(|_| file.write_all(b"WAVEfmt "))
        .and_then(|_| file.write_all(&16_u32.to_le_bytes()))
        .and_then(|_| file.write_all(&1_u16.to_le_bytes()))
        .and_then(|_| file.write_all(&1_u16.to_le_bytes()))
        .and_then(|_| file.write_all(&SAMPLE_RATE.to_le_bytes()))
        .and_then(|_| file.write_all(&(SAMPLE_RATE * 2).to_le_bytes()))
        .and_then(|_| file.write_all(&2_u16.to_le_bytes()))
        .and_then(|_| file.write_all(&16_u16.to_le_bytes()))
        .and_then(|_| file.write_all(b"data"))
        .and_then(|_| file.write_all(&data_bytes.to_le_bytes()))
        .map_err(|error| format!("Could not write fixture WAV header: {error}"))?;

    let mut pcm = Vec::with_capacity(data_bytes as usize);
    for sample_index in 0..sample_count {
        let time = f64::from(sample_index) / f64::from(SAMPLE_RATE);
        let envelope = 0.55 + 0.3 * (2.0 * PI * 0.28 * time).sin();
        let value = ((2.0 * PI * frequency * time).sin() * 0.68
            + (2.0 * PI * (frequency * 1.503) * time).sin() * 0.19)
            * envelope;
        let sample = (value * f64::from(i16::MAX) * 0.45) as i16;
        pcm.extend_from_slice(&sample.to_le_bytes());
    }
    file.write_all(&pcm)
        .map_err(|error| format!("Could not write fixture WAV samples: {error}"))?;
    Ok(pcm)
}
